"""Regenerate custom_components/arpa_veneto_meteo/comuni_coords.py from Wikidata.

The config flow sorts the weather stations from the municipality chosen in the
first step. ARPAV ``meteo_comuni`` gives each municipality its ISTAT code but no
coordinates, so this script builds the ISTAT -> (lat, lon) table from Wikidata
(ISTAT ID P635, coordinate location P625; Wikidata data is CC0).

Former municipalities are kept on purpose: after a merger ARPAV may still list
the old ISTAT codes. When an ISTAT code is shared by more than one item, the
item that is an Italian comune (Q747074) wins.

Run it by hand when municipalities change; Home Assistant never calls Wikidata:

    python3 scripts/generate_comuni_coords.py
"""

from __future__ import annotations

import json
import pathlib
import re
import urllib.parse
import urllib.request

ENDPOINT = "https://query.wikidata.org/sparql"
USER_AGENT = "ha-arpav-meteo-comuni-generator/1.0 (https://github.com/fabioscarparo/ha-arpav-meteo)"
# Veneto provinces: 023 Verona ... 029 Rovigo
QUERY = """
SELECT ?item ?istat ?coord ?isComune WHERE {
  ?item wdt:P635 ?istat ; wdt:P625 ?coord .
  FILTER(REGEX(?istat, "^02[3-9][0-9]{3}$"))
  BIND(EXISTS { ?item wdt:P31 wd:Q747074 } AS ?isComune)
}
"""
OUTPUT = (
    pathlib.Path(__file__).resolve().parents[1]
    / "custom_components"
    / "arpa_veneto_meteo"
    / "comuni_coords.py"
)
POINT = re.compile(r"^Point\(([-0-9.]+) ([-0-9.]+)\)$")
HEADER = '''"""Coordinates of the Veneto municipalities, keyed by ISTAT code.

Generated by scripts/generate_comuni_coords.py from Wikidata (CC0): do not edit
by hand. Former municipalities are included because ARPAV may still list them.
"""

COMUNI_COORDS: dict[int, tuple[float, float]] = {
'''


def fetch() -> list[dict[str, dict[str, str]]]:
    """Run the SPARQL query and return its bindings."""
    url = f"{ENDPOINT}?{urllib.parse.urlencode({'query': QUERY})}"
    request = urllib.request.Request(
        url,
        headers={"Accept": "application/sparql-results+json", "User-Agent": USER_AGENT},
    )
    with urllib.request.urlopen(request, timeout=120) as response:
        return json.load(response)["results"]["bindings"]


def build(bindings: list[dict[str, dict[str, str]]]) -> dict[int, tuple[float, float]]:
    """Reduce the bindings to one (lat, lon) per ISTAT code, comuni first."""
    best: dict[int, tuple[bool, str, float, float]] = {}
    for row in bindings:
        match = POINT.match(row["coord"]["value"])
        if match is None:
            continue
        istat = int(row["istat"]["value"])
        lon, lat = float(match.group(1)), float(match.group(2))
        is_comune = row.get("isComune", {}).get("value") == "true"
        candidate = (is_comune, row["item"]["value"], lat, lon)
        current = best.get(istat)
        # a comune beats any other item; between equals keep a stable choice
        if current is None or (candidate[0], candidate[1]) > (current[0], current[1]):
            best[istat] = candidate
    return {istat: (round(v[2], 4), round(v[3], 4)) for istat, v in sorted(best.items())}


def render(coords: dict[int, tuple[float, float]]) -> str:
    """Return the content of the generated module."""
    lines = [f"    {istat}: ({lat}, {lon})," for istat, (lat, lon) in coords.items()]
    return HEADER + "\n".join(lines) + "\n}\n"


def main() -> None:
    """Write the generated module."""
    coords = build(fetch())
    OUTPUT.write_text(render(coords), encoding="utf-8")
    print(f"{len(coords)} municipalities written to {OUTPUT}")  # noqa: T201


if __name__ == "__main__":
    main()
